"""Reproducible single-file installer containing only public runtime sources."""
import base64
import gzip
import hashlib
import io
import tarfile
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent


def build(destination):
    paths=[ROOT/'pyproject.toml',ROOT/'LICENSE',ROOT/'scripts/setup.sh']
    paths += [p for p in (ROOT/'donino_link').rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.suffix!='.pyc']
    archive=io.BytesIO()
    with tarfile.open(fileobj=archive,mode='w',format=tarfile.GNU_FORMAT) as tar:
        for path in sorted(paths):
            content=path.read_bytes()
            info=tarfile.TarInfo('project/'+path.relative_to(ROOT).as_posix())
            info.size=len(content);info.mode=0o600;info.uid=info.gid=0;info.mtime=0
            tar.addfile(info,io.BytesIO(content))
    # Python 3.11/3.12 inherit zlib's OS byte; 3.13 uses 255. Normalize it.
    compressed=bytearray(gzip.compress(archive.getvalue(),compresslevel=9,mtime=0));compressed[9]=255
    payload=bytes(compressed)
    checksum=hashlib.sha256(payload).hexdigest()
    encoded=base64.b64encode(payload).decode()
    lines='\n'.join(encoded[i:i+76] for i in range(0,len(encoded),76))
    shell='''#!/usr/bin/env bash
# Donino Tunnel standalone installer. Generated by scripts/build-standalone.py.
# Copy THIS file to each server and run: sudo bash install-donino.sh
set -Eeuo pipefail
umask 077
[[ $(id -u) -eq 0 ]] || { echo 'Run: sudo bash install-donino.sh' >&2; exit 1; }
for dependency in base64 tar sha256sum mktemp; do command -v "$dependency" >/dev/null || { echo "Missing: $dependency" >&2; exit 1; }; done
bundle_dir=$(mktemp -d /var/tmp/donino-standalone-XXXXXX)
trap 'rm -rf -- "$bundle_dir"' EXIT
base64 --decode > "$bundle_dir/runtime.tar.gz" <<'__DONINO_RUNTIME__'
'''+lines+'''
__DONINO_RUNTIME__
expected='''+checksum+'''
actual=$(sha256sum "$bundle_dir/runtime.tar.gz")
[[ "${actual%% *}" == "$expected" ]] || { echo 'Embedded runtime checksum failed.' >&2; exit 1; }
tar -xzf "$bundle_dir/runtime.tar.gz" -C "$bundle_dir"
bash "$bundle_dir/project/scripts/setup.sh" "$@"
'''
    destination=Path(destination);destination.write_text(shell);destination.chmod(0o755)
    return {'file':str(destination),'bytes':destination.stat().st_size,'runtime_sha256':checksum,'files':len(paths)}


if __name__=='__main__':
    import argparse,json
    parser=argparse.ArgumentParser();parser.add_argument('--output',default=str(ROOT/'install-donino.sh'))
    print(json.dumps(build(parser.parse_args().output)))
