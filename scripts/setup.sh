#!/usr/bin/env bash
# Run locally on EACH server. No SSH key/password is copied by the operator.
set -Eeuo pipefail
umask 077
[[ $(id -u) -eq 0 ]] || { echo 'Run: sudo bash scripts/setup.sh' >&2; exit 1; }
source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
role='';address='';forward=();upgrade=false
while (($#)); do
  case "$1" in
    --role) role=${2:?}; shift 2;;
    --address) address=${2:?}; shift 2;;
    --panel-port|--agent-port|--password-file) forward+=("$1" "${2:?}"); shift 2;;
    --upgrade) upgrade=true; forward+=("$1"); shift;;
    --no-open-ufw|--allow-private-peers) forward+=("$1"); shift;;
    --help) echo 'sudo bash scripts/setup.sh [--role iran|foreign] [--address IP_OR_DNS] [--panel-port PORT] [--agent-port PORT] [--upgrade]'; exit 0;;
    *) echo "Unknown option: $1" >&2; exit 1;;
  esac
done
if [[ -f /etc/donino-link/current/node.json ]]; then
  mapfile -t existing_node < <(python3 - <<'PYCONFIG'
import json
from pathlib import Path
cfg=json.loads(Path('/etc/donino-link/current/node.json').read_text())
print(cfg['role']);print(cfg.get('public_address',''))
PYCONFIG
)
  if [[ -n "$role" && "$role" != "${existing_node[0]:-}" ]]; then
    echo 'This server already has the other role. Upgrade preserves the existing role.' >&2
    exit 1
  fi
  if ! $upgrade; then
    echo "Donino is already installed here (${existing_node[0]:-})."
    echo '1) Upgrade: keep the current role, address, panel password and tunnel settings'
    echo '2) Cancel'
    read -r -p 'Choose [1/2]: ' answer
    [[ "$answer" == 1 ]] || { echo 'Installation cancelled; existing settings kept.'; exit 0; }
    upgrade=true;forward+=(--upgrade)
  fi
  [[ -n "$role" ]] || role=${existing_node[0]:-}
  [[ -n "$address" ]] || address=${existing_node[1]:-}
  echo "Upgrading this server as $role; existing configuration and password are preserved."
fi
if [[ -z "$role" ]]; then
  echo 'Donino Tunnel — install this server'
  echo '1) Iran: control panel and automatic two-node installer'
  echo '2) Foreign: monitoring panel, pairing and origin health'
  while [[ -z "$role" ]]; do
    read -r -p 'Server role [1/2]: ' answer
    case "$answer" in 1|iran) role=iran;; 2|foreign) role=foreign;; *) echo 'Select 1 (Iran) or 2 (Foreign).' >&2;; esac
  done
fi
[[ "$role" == iran || "$role" == foreign ]] || exit 1
[[ -n "$address" ]] || read -r -p 'Public IP/domain of THIS server: ' address
source "$source_dir/donino_link/resources/platform.sh"
donino_platform
[[ -d /run/systemd/system ]] || { echo 'A running systemd is required.' >&2; exit 1; }
donino_apt update -q
packages=(python3 python3-venv python3-pip openssl ca-certificates openssh-client)
[[ "$role" != foreign ]] || packages+=(openssh-server)
donino_apt install -y -q --no-install-recommends "${packages[@]}"
python3 -c 'import sys; assert sys.version_info >= (3,10), "Python 3.10+ required"'
if [[ "$role" == foreign ]]; then
  ssh-keygen -A
  /usr/sbin/sshd -t
  systemctl enable --now ssh.service
fi
stage=$(mktemp -d /var/tmp/donino-setup-XXXXXX)
trap 'rm -rf -- "$stage"' EXIT
cp -a "$source_dir/donino_link" "$source_dir/pyproject.toml" "$stage/"
source "$source_dir/donino_link/resources/python-runtime.sh"
donino_python_runtime "$stage"
"$stage/venv/bin/donino-link" init-node --role "$role" --address "$address" "${forward[@]}"
services=(donino-link.service)
if [[ "$role" == iran ]]; then services+=(donino-control.service);else services+=(donino-foreign-agent.service ssh.service);fi
for service in "${services[@]}"; do
  systemctl is-active --quiet "$service"
  systemctl is-enabled --quiet "$service"
done
panel_url=$("$stage/venv/bin/python" - "$address" <<'PYURL'
import sys
from donino_link.config import load_config,endpoint
cfg=load_config('/etc/donino-link/current/node.json')
host=cfg.get('public_address') or sys.argv[1];host='['+host+']' if ':' in host else host
scheme='https' if cfg['panel'].get('tls_cert') else 'http'
print(scheme+'://'+host+':'+str(endpoint(cfg['panel']['listen'])[1]))
PYURL
)
echo
echo "Donino $role panel is installed. Services are active and enabled at boot."
echo "Panel URL: $panel_url"
if [[ "$role" == foreign ]]; then
  echo 'Sign in, generate a pairing code, and enter it in the Iran panel.'
else
  echo 'Sign in and enter the code generated by the Foreign panel to pair the servers.'
fi
echo 'Provider firewall: allow the panel port, foreign pairing TCP port (default 9444), and the tunnel ports shown by the panel.'
